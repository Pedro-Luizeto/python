frase = 'Eu amo python !'
len(frase) # Mostra o tamanho da string


frase.count('o') # Conta quantas vezes a letra 'o' aparece na string
frase.find('python') # Mostra a posição da palavra 'python' na string
frase.replace('python', 'Java') # Substitui a palavra 'python' por 'Java'
frase.lower() # Converte a string para minúsculas
frase.upper() # Converte a string para maiúsculas
frase.capitalize() # Converte a primeira letra da string para maiúscula
frase.strip() # Remove espaços em branco no início e no final da string
frase.split() # Divide a string em uma lista de palavras
frase.title() # Converte a primeira letra de cada palavra para maiúscula
